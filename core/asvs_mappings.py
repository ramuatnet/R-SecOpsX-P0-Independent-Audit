# CWE classes that ASVS v4.0.3 does not cite anywhere in its own enumeration.
# A finding carrying one of these is NOT mapped to an ASVS requirement, and that
# is recorded rather than papered over. Computed at import from the catalogue so
# it cannot drift from the pinned dataset.
def unreferenced_cwe(cwe_ids=()) -> dict:
    """Which of the supplied CWE classes ASVS v4.0.3 does not cite anywhere.

    Reported rather than silently mapped to a near neighbour. A weakness class
    ASVS does not enumerate has no requirement to attribute, and inventing a
    plausible one is exactly the fabrication this project forbids.
    """
    out = {}
    for c in cwe_ids:
        cid = str(c or "").strip().upper()
        if not cid:
            continue
        m = re.search(r"CWE-\d+", cid)
        cid = m.group(0) if m else ""
        if cid and cid not in ASVS_BY_CWE:
            out[cid] = "ASVS v4.0.3 does not cite this CWE in its enumeration."
    return out


def asvs_catalogue_cwe_coverage() -> dict:
    """How many catalogue requirements carry an ASVS-published CWE edge."""
    with_edge = {
        r for ids in ASVS_BY_CWE.values() for r in ids if r in ASVS_REQUIREMENTS
    }
    return {
        "total": len(ASVS_REQUIREMENTS),
        "with_cwe_edge": len(with_edge),
        "without_cwe_edge": len(ASVS_REQUIREMENTS) - len(with_edge),
    }

UNMAPPED_RATIONALE = (
    "No ASVS v4.0.3 requirement was attributed to this finding. Either the "
    "requirement's subject is not a weakness class ASVS enumerates, or the "
    "weakness class is one ASVS does not cite. Absence of a mapping is not a "
    "clean result: an ASVS requirement with no finding against it may still be "
    "unmet, because most ASVS requirements are verification statements that no "
    "source scan can decide."
)


def qualified(requirement_id: str) -> str:
    """Return the version-qualified id OWASP asks tools to emit.

    A bare `V5.3.4` is ambiguous across ASVS versions; OWASP's own guidance is
    to qualify it. Never render the bare form.
    """
    rid = str(requirement_id or "").strip()
    if not rid:
        return ""
    if rid.startswith(ASVS_ID_PREFIX):
        return rid
    return ASVS_ID_PREFIX + rid


def requirement_label(requirement_id: str) -> str:
    """'V5.3.4 Validation, Sanitization and Encoding > Output Encoding...' form."""
    rid = str(requirement_id or "").strip()
    spec = ASVS_REQUIREMENTS.get(rid) or {}
    chapter = ASVS_CHAPTERS.get(spec.get("chapter") or "", "")
    section = ASVS_SECTIONS.get(spec.get("section") or "", "")
    bits = [qualified(rid)]
    if section:
        bits.append(section)
    if chapter and chapter != section:
        bits.append(chapter)
    return " - ".join(bits)


def evidence_class(requirement_id: str) -> str:
    """Classify how a requirement's subject can be evidenced.

    Derived from the dataset, not asserted per requirement by hand:

    ASVS cites a CWE for a requirement when that requirement addresses a
    specific weakness class. Those are the requirements whose subject a static
    scanner can speak to, because that is exactly the class of question a
    weakness detector answers. A requirement with no CWE cross-reference is
    overwhelmingly a process, architecture, runtime-configuration or
    verification-activity statement.

    This is a heuristic over the dataset, not a per-requirement judgement, and it
    is the weakest part of this module. It is reported so a reader can see which
    bucket a number came from, and it is why no figure derived from it is
    presented as an ASVS coverage score.
    """
    spec = ASVS_REQUIREMENTS.get(str(requirement_id or "").strip()) or {}
    return EVIDENCE_STATIC if spec.get("cwe") else EVIDENCE_RUNTIME


def asvs_reference(rule_id: str = "", vuln_type: str = "", cwe: str = "") -> dict:
    """Pinned ASVS v4.0.3 attribution for one finding. Fails closed.

    DIRECT  reached through ASVS's OWN `cwe` cross-reference column. The linkage
            is OWASP's, not this project's.
    RELATED reached through the curated vuln_type table, where each edge is
            justified by a keyword in that requirement's own text. The linkage is
            this project's judgement, so it is never reported as DIRECT.
    UNMAPPED no defensible edge. Reported, with a rationale, never dropped.
    """
    cwe_id = str(cwe or "").strip().upper()
    # Always reduce to the bare CWE-nnn token. Findings carry the class with a
    # trailing description ("CWE-798 - Use of Hard-coded Credentials") as well
    # as the bare form, and an exact-match lookup against a decorated string
    # silently yields UNMAPPED.
    m = re.search(r"CWE-\d+", cwe_id)
    cwe_id = m.group(0) if m else ""

    vtype = str(vuln_type or "").strip().lower()

    base = {
        "asvs_id": "",
        "asvs_requirement": "",
        "asvs_label": "",
        "asvs_chapter": "",
        "asvs_section": "",
        "asvs_section_name": "",
        "asvs_levels": "",
        "asvs_evidence_class": "",
        "asvs_related": [],
        "asvs_mapping_mode": UNMAPPED,
        "asvs_rationale": "",
        "asvs_dataset": ASVS_DATASET_LABEL,
        "asvs_version": ASVS_VERSION,
        "asvs_license": ASVS_LICENSE,
        "asvs_source_url": ASVS_SOURCE_URL,
        "asvs_semantics": (
            "Evidence relevant to this ASVS requirement. NOT a statement that the "
            "requirement is unmet, and NOT an ASVS compliance claim."
        ),
    }

    direct = []
    if cwe_id:
        direct = [r for r in ASVS_BY_CWE.get(cwe_id, [])]
        # A tombstoned id can never be emitted even if an edge pointed at it.
        direct = [r for r in direct if r in ASVS_REQUIREMENTS]

    related = [r for r in ASVS_BY_VULN_TYPE.get(vtype, []) if r in ASVS_REQUIREMENTS]

    if direct:
        chosen = direct[0]
        spec = ASVS_REQUIREMENTS[chosen]
        base["asvs_id"] = qualified(chosen)
        base["asvs_requirement"] = chosen
        base["asvs_label"] = requirement_label(chosen)
        base["asvs_chapter"] = spec["chapter"]
        base["asvs_section"] = spec["section"]
        base["asvs_section_name"] = ASVS_SECTIONS.get(spec["section"], "")
        base["asvs_levels"] = _levels_text(spec)
        base["asvs_evidence_class"] = evidence_class(chosen)
        base["asvs_related"] = [qualified(r) for r in direct[1:] + related
                                if r != chosen]
        base["asvs_mapping_mode"] = DIRECT
        base["asvs_rationale"] = (
            "ASVS v4.0.3 cites %s for requirement %s in its own enumeration, and "
            "this finding carries that CWE." % (cwe_id, qualified(chosen))
        )
        return base

    if related:
        chosen = related[0]
        spec = ASVS_REQUIREMENTS[chosen]
        base["asvs_id"] = qualified(chosen)
        base["asvs_requirement"] = chosen
        base["asvs_label"] = requirement_label(chosen)
        base["asvs_chapter"] = spec["chapter"]
        base["asvs_section"] = spec["section"]
        base["asvs_section_name"] = ASVS_SECTIONS.get(spec["section"], "")
        base["asvs_levels"] = _levels_text(spec)
        base["asvs_evidence_class"] = evidence_class(chosen)
        base["asvs_related"] = [qualified(r) for r in related[1:]]
        base["asvs_mapping_mode"] = RELATED
        base["asvs_rationale"] = (
            "Linked through this project's vuln_type table (%s), justified by "
            "that requirement's own text naming the construct. Not an ASVS "
            "cross-reference, so reported as RELATED rather than DIRECT." % vtype
        )
        return base

    base["asvs_rationale"] = UNMAPPED_RATIONALE
    return base


def _levels_text(spec: dict) -> str:
    """Render verification levels verbatim, preserving non-boolean qualifiers."""
    parts = []
    for label, key in (("L1", "level1"), ("L2", "level2"), ("L3", "level3")):
        val = str((spec or {}).get(key) or "").strip()
        if val:
            parts.append("%s=%s" % (label, val))
    return ", ".join(parts)


def enrich_with_asvs(finding: dict) -> dict:
    finding.update(asvs_reference(
        finding.get("rule_id", ""),
        finding.get("vuln_type", ""),
        finding.get("cwe", ""),
    ))
    return finding


def asvs_coverage(cwes=(), vuln_types=()) -> dict:
    """Coverage summary over the catalogue, with every denominator stated.

    Ratios here are about which catalogue entries this release can reach. They
    are NOT an ASVS compliance score and must not be presented as one: the
    overwhelming majority of ASVS requirements are verification activities that
    no source scan performs, so a low ratio is expected and is not a defect.
    """
    from collections import Counter

    def tally(keys, resolve):
        counts = Counter()
        mapped, unmapped = [], []
        keys = list(keys)
        for k in keys:
            mode = resolve(k)["asvs_mapping_mode"]
            counts[mode] += 1
            (mapped if mode != UNMAPPED else unmapped).append(k)
        return {
            "total": len(keys),
            "by_mode": dict(counts),
            "mapped": sorted(mapped),
            "unmapped": sorted(unmapped),
            "coverage_ratio": (len(mapped) / len(keys)) if keys else 0.0,
        }

    families = {
        "cwe": tally(cwes, lambda k: asvs_reference("", "", k)),
        "vuln_type": tally(vuln_types, lambda k: asvs_reference("", k, "")),
    }
    total = sum(f["total"] for f in families.values())
    mapped = sum(len(f["mapped"]) for f in families.values())
    families["combined"] = {
        "total": total,
        "mapped": mapped,
        "unmapped": total - mapped,
        "coverage_ratio": (mapped / total) if total else 0.0,
    }

    reachable = sorted({
        r for c in cwes
        for r in ASVS_BY_CWE.get(str(c).strip().upper(), [])
        if r in ASVS_REQUIREMENTS
    } | {
        r for v in vuln_types
        for r in ASVS_BY_VULN_TYPE.get(str(v).strip().lower(), [])
        if r in ASVS_REQUIREMENTS
    }, key=lambda x: tuple(int(p) for p in x[1:].split(".")))

    families["requirements_reachable"] = [qualified(r) for r in reachable]
    families["requirements_reachable_count"] = len(reachable)
    families["catalogue_size"] = len(ASVS_REQUIREMENTS)
    families["catalogue_with_cwe_edge"] = len({
        r for ids in ASVS_BY_CWE.values() for r in ids if r in ASVS_REQUIREMENTS
    })
    families["catalogue_without_cwe_edge"] = (
        len(ASVS_REQUIREMENTS) - families["catalogue_with_cwe_edge"]
    )
    families["tombstones_excluded"] = len(ASVS_EXCLUDED_TOMBSTONES)
    families["dataset"] = ASVS_DATASET_LABEL
    families["semantics"] = (
        "Ratios describe reachability into ASVS's catalogue, not compliance. "
        "ASVS is a verification standard: most requirements are verification "
        "activities, so most are unreachable by design."
    )
    return families
