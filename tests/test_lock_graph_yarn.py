"""Yarn v1 verified-edge extractor tests (R2.3).

Every expected graph below is an INDEPENDENT hand-authored expectation --
the tests never validate the extractor against its own output. Real-corpus
validation lives in tools/oracle_yarn.py (yarn CLI cross-check) and the
R2_3 benchmark record; these fixtures pin the 16 mandatory scenario classes
with minimal synthetic lockfiles (marked SYNTHETIC in each fixture).
"""

from analysis.lock_graph import contract
from analysis.lock_graph import registry
from analysis.lock_graph.yarn import extract


def _write(tmp_path, text):
    lock = tmp_path / "yarn.lock"
    lock.write_text(text, encoding="utf-8")
    return str(lock)


HEADER = "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n"


def _verified_pairs(result):
    return {(e["parent_name"], e["parent_version"],
             e["child_name"], e["child_version"])
            for e in result["edges"] if e["confidence"] == "VERIFIED"}


# 1 + 2 + 3: direct, one-level transitive, multi-level chains -----------------
CHAIN = HEADER + '''\
alpha@^1.0.0:
  version "1.2.0"
  resolved "https://registry.yarnpkg.com/alpha/-/alpha-1.2.0.tgz"
  dependencies:
    beta "^1.0.0"

beta@^1.0.0:
  version "1.5.0"
  resolved "https://registry.yarnpkg.com/beta/-/beta-1.5.0.tgz"
  dependencies:
    gamma "^2.0.0"

gamma@^2.0.0:
  version "2.3.4"
  resolved "https://registry.yarnpkg.com/gamma/-/gamma-2.3.4.tgz"
  dependencies:
    delta ">=1 <2"

delta@^1.0.0:
  version "1.9.0"
  resolved "https://registry.yarnpkg.com/delta/-/delta-1.9.0.tgz"
'''


def test_direct_one_level_and_multilevel_chain(tmp_path):
    # SYNTHETIC: independent expected graph -- alpha->beta->gamma->delta
    result = extract(_write(tmp_path, CHAIN))
    assert result["graph_status"] == "VERIFIED_EDGES_AVAILABLE"
    assert result["engine"] == "YARN_LOCK_GRAPH_V1"
    assert _verified_pairs(result) == {
        ("alpha", "1.2.0", "beta", "1.5.0"),
        ("beta", "1.5.0", "gamma", "2.3.4"),
        ("gamma", "2.3.4", "delta", "1.9.0"),
    }
    # constraints and resolution evidence travel with the edge
    edge = next(e for e in result["edges"] if e["child_name"] == "delta")
    assert edge["requested_spec"] == ">=1 <2"
    assert edge["parent_purl"] == "pkg:npm/gamma@2.3.4"
    assert edge["fingerprint"].startswith("sha256:")


# 4: multiple parents ---------------------------------------------------------
MULTI_PARENT = HEADER + '''\
left@^1.0.0:
  version "1.0.0"
  dependencies:
    shared "^3.0.0"

right@^2.0.0:
  version "2.1.0"
  dependencies:
    shared "^3.0.0"

shared@^3.0.0:
  version "3.4.5"
'''


def test_multiple_parents_each_get_own_edge(tmp_path):
    # SYNTHETIC: two parents declare the same child
    result = extract(_write(tmp_path, MULTI_PARENT))
    pairs = _verified_pairs(result)
    assert ("left", "1.0.0", "shared", "3.4.5") in pairs
    assert ("right", "2.1.0", "shared", "3.4.5") in pairs
    assert len(pairs) == 2


# 5: duplicate package versions ----------------------------------------------
DUP_VERSIONS = HEADER + '''\
app@^1.0.0:
  version "1.0.0"
  dependencies:
    lib "^1.0.0"

old@^1.0.0:
  version "1.0.0"
  dependencies:
    lib "^1.0.0"

lib@^1.0.0:
  version "1.0.0"

lib@^2.0.0:
  version "2.0.0"
'''


def test_duplicate_package_versions_disambiguate_by_constraint(tmp_path):
    # SYNTHETIC: lib exists at 1.0.0 and 2.0.0; constraint ^1.0.0 is unique
    result = extract(_write(tmp_path, DUP_VERSIONS))
    pairs = _verified_pairs(result)
    assert ("app", "1.0.0", "lib", "1.0.0") in pairs
    assert ("old", "1.0.0", "lib", "1.0.0") in pairs


def test_duplicate_package_versions_ambiguous_when_constraint_spans(tmp_path):
    # SYNTHETIC: constraint >=1 matches BOTH instances -> AMBIGUOUS,
    # candidates disclosed, no arbitrary parent binding
    lockfile = HEADER + '''\
app@^1.0.0:
  version "1.0.0"
  dependencies:
    lib ">=1.0.0"

lib@^1.0.0:
  version "1.0.0"

lib@^2.0.0:
  version "2.0.0"
'''
    result = extract(_write(tmp_path, lockfile))
    amb = [e for e in result["edges"] if e["confidence"] == "AMBIGUOUS"]
    assert len(amb) == 1
    assert amb[0]["child_version"] == ""
    assert amb[0]["ambiguity"]["candidates"] == ["1.0.0", "2.0.0"]
    assert amb[0]["resolution_status"] == "MULTIPLE_CANDIDATES"


