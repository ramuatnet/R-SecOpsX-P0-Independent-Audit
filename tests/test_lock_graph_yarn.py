# 11: missing versions --------------------------------------------------------
MISSING_VERSION = HEADER + '''\
broken@^1.0.0:
  resolved "https://registry.yarnpkg.com/broken/-/broken-1.0.0.tgz"

app@^1.0.0:
  version "1.0.0"
  dependencies:
    broken "^1.0.0"
'''


def test_entry_without_version_is_invalid_not_parent(tmp_path):
    # SYNTHETIC: an entry with no resolved version can never be a parent;
    # its declaration stays UNRESOLVED, the record is counted
    result = extract(_write(tmp_path, MISSING_VERSION))
    assert _verified_pairs(result) == set()
    assert result["tallies"]["invalid_records"] >= 1
    unresolved = [e for e in result["edges"]
                  if e["child_name"] == "broken"]
    assert unresolved and unresolved[0]["confidence"] == "UNRESOLVED"


# 12: ambiguous resolution ----------------------------------------------------
def test_ambiguous_resolution_never_selects(tmp_path):
    # covered structurally by test_duplicate_package_versions_ambiguous...
    # plus: AMBIGUOUS edges never carry a fingerprint
    result = extract(_write(tmp_path, DUP_VERSIONS))
    for edge in result["edges"]:
        if edge["confidence"] == "AMBIGUOUS":
            assert "fingerprint" not in edge


