def test_no_top_level_psycopg_import():
    # psycopg is absent on offline boxes -- a column-0 import would make
    # the whole serve package unimportable; it must stay lazy
    src = (pathlib.Path(__file__).resolve().parents[1]
           / "analysis" / "serve" / "storage.py")
    tree = ast.parse(src.read_text(encoding="utf-8"))
    top = []
    for node in tree.body:
        if isinstance(node, ast.Import):
            top.extend(a.name for a in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module:
            top.append(node.module)
    assert "psycopg" not in top


