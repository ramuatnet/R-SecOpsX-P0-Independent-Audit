def test_migration_adds_missing_tenant_column(tmp_path, monkeypatch):
    db = tmp_path / "rsx_t94_legacy.db"
    conn = sqlite3.connect(db.as_posix())
    conn.executescript(
        """
        CREATE TABLE jobs (
            id TEXT PRIMARY KEY, target TEXT, out TEXT,
            status TEXT, attempts INTEGER, last_error TEXT,
            created_at REAL, updated_at REAL);
        CREATE TABLE schedules (
            id TEXT PRIMARY KEY, cron TEXT, target TEXT, out TEXT,
            created_at REAL, last_tick REAL);
        CREATE TABLE events (
            seq INTEGER PRIMARY KEY AUTOINCREMENT,
            kind TEXT, payload TEXT, at REAL);
        CREATE TABLE webhooks (
            id TEXT PRIMARY KEY, url TEXT, active INTEGER);
        INSERT INTO jobs (id, target, out, status, attempts, last_error,
                          created_at, updated_at)
            VALUES ('legacy', 'app/', NULL, 'done', 1, NULL, 1.0, 2.0);
        """)
    conn.commit()
    conn.close()
    _install_fake_psycopg(monkeypatch, db_path=db.as_posix())
    b = PostgresBackend("postgres://u:p@h/legacy")
    try:
        row = b.job("legacy")
        assert row is not None and row["tenant"] == ""
        assert b.list_jobs(tenant="acme") == []   # '' != 'acme'
        assert b.list_jobs(tenant="") == [row]    # unscoped sees it
    finally:
        b.close()


