def test_full_scenario_parity(monkeypatch):
    def scenario(b):
        out = {}
        b.enqueue_job({"id": "job_a", "target": "app/", "out": None,
                       "status": "queued", "attempts": 0,
                       "last_error": None}, now=100.0)
        b.enqueue_job({"id": "job_b", "target": "svc/", "out": "o/",
                       "status": "queued", "attempts": 0,
                       "last_error": None, "tenant": "acme"}, now=101.0)
        out["job"] = b.job("job_a")
        out["job_missing"] = b.job("nope")
        out["jobs"] = b.list_jobs()
        b.update_job("job_a", status="done", attempts=1, now=102.0)
        out["updated"] = b.job("job_a")
        out["seq1"] = b.append_event("job.enqueued", {"id": "job_a"},
                                     at=100.5)
        out["seq2"] = b.append_event("job.done", {"id": "job_a"},
                                     at=102.5, tenant="acme")
        out["events"] = b.events_since(0)
        b.insert_schedule({"id": "sch_1", "cron": "0 * * * *",
                           "target": "app/", "out": None}, now=103.0)
        b.set_last_tick("sch_1", 104)
        out["schedules"] = b.schedules()
        out["wh_bare"] = b.register_webhook("https://hooks.test/a")
        out["wh_acme"] = b.register_webhook("https://hooks.test/a",
                                            tenant="acme")
        out["webhooks"] = b.webhooks()
        b.upsert_delivery(out["seq1"], out["wh_bare"], 1, 200, at=110.0)
        b.upsert_delivery(out["seq1"], out["wh_bare"], 2, -1, at=120.0)
        out["delivery"] = b.delivery_recorded(out["seq1"], out["wh_bare"])
        out["deliveries"] = b.deliveries()
        return out

    sq, pg = _run_backends(scenario, monkeypatch)
    assert sq == pg


