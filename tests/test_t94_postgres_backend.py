# ---------------------------------------------------------------------------
# test double: a psycopg-shaped module whose connect() hands back a shim
# connection that translates the Postgres dialect onto a real sqlite3
# database (placeholders %s->?, IDENTITY->AUTOINCREMENT, ...) so the
# parity scenarios exercise REAL SQL round-trips without a live server.
# ---------------------------------------------------------------------------


def _translate(sql: str) -> str:
    out = sql.replace("%s", "?")
    out = out.replace(
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        "INTEGER PRIMARY KEY AUTOINCREMENT")
    out = out.replace("DOUBLE PRECISION", "REAL")
    out = out.replace(" BIGINT", " INTEGER")
    out = out.replace("ADD COLUMN IF NOT EXISTS", "ADD COLUMN")
    return out


class _FakeCursor:
    """Cursor over canned rows with a one-column description."""

    description = (("column_name", None, None, None, None, None, None),)

    def __init__(self, rows):
        self._rows = list(rows)

    def fetchall(self):
        return list(self._rows)

    def fetchone(self):
        return self._rows[0] if self._rows else None


class _ShimConn:
    """psycopg3-shaped connection over sqlite3 (statement-recording)."""

    def __init__(self, conn, record=None):
        self._conn = conn
        self.record = record if record is not None else []

    def execute(self, sql, params=()):
        self.record.append((sql, tuple(params)))
        if "information_schema.columns" in sql:
            # the PG migration query -- answer from sqlite's own catalog
            table = params[0]
            rows = self._conn.execute(
                f"PRAGMA table_info({table})").fetchall()  # noqa: S608
            return _FakeCursor([(r[1],) for r in rows])
        return self._conn.execute(_translate(sql), params)

    def __enter__(self):
        self._conn.__enter__()
        return self

    def __exit__(self, *exc):
        return self._conn.__exit__(*exc)

    def close(self):
        self._conn.close()


def _install_fake_psycopg(monkeypatch, db_path=":memory:", record=None):
    """Force the driver-present path with the sqlite-translating shim."""
    mod = types.ModuleType("psycopg")
    mod.urls = []

    def connect(url):
        mod.urls.append(url)
        return _ShimConn(sqlite3.connect(db_path), record=record)

    mod.connect = connect
    monkeypatch.setitem(sys.modules, "psycopg", mod)
    return mod


def _run_backends(scenario, monkeypatch):
    """Run one scenario against BOTH backends; return (sq, pg) results."""
    sq = SqliteBackend(":memory:")
    _install_fake_psycopg(monkeypatch)
    pg = PostgresBackend("postgres://user:pw@host/db")
    try:
        return scenario(sq), scenario(pg)
    finally:
        sq.close()
        pg.close()


