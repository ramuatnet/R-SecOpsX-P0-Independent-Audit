def test_webhook_id_canon_parity_across_backends(monkeypatch):
    url = "https://hooks.example/deploy"
    sq = SqliteBackend(":memory:")
    _install_fake_psycopg(monkeypatch)
    pg = PostgresBackend("postgres://u:p@h/d")
    try:
        for tenant in (None, "acme", "globex"):
            sid, pid = (sq.register_webhook(url, tenant=tenant),
                        pg.register_webhook(url, tenant=tenant))
            assert sid == pid == webhook_id_for(url, tenant)
        # frozen T-8.2 digest: bare url, unscoped
        assert sq.register_webhook("https://hooks.example/other") == \
            "wh_" + hashlib.sha256(
                "https://hooks.example/other".encode()).hexdigest()[:12]
    finally:
        sq.close()
        pg.close()


