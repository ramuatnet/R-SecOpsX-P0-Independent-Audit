def test_registry_dispatches_cargo_files():
    assert {"Cargo.lock", "Cargo.toml"} <= registry.LOCKFILE_NAMES


def test_run_to_run_determinism(tmp_path):
    a = registry.extract_for_file(_write(tmp_path, LOCK_V4, "Cargo.lock"))
    b = registry.extract_for_file(_write(tmp_path, LOCK_V4, "Cargo.lock"))
    assert a == b


def test_confidence_vocabulary_pinned(tmp_path):
    result = registry.extract_for_file(_write(tmp_path, LOCK_V4, "Cargo.lock"))
    for edge in result["edges"]:
        assert edge["confidence"] in (
            contract.VERIFIED, contract.AMBIGUOUS, contract.UNRESOLVED,
            contract.UNSUPPORTED, contract.INVALID)
