def test_lock_scope_never_invented(tmp_path):
    # the lockfile does not record kinds: scope stays unknown, never dev/
    # build guesses
    result = registry.extract_for_file(_write(tmp_path, LOCK_V4, "Cargo.lock"))
    for edge in result["edges"]:
        assert edge["scope"] == "unknown"
