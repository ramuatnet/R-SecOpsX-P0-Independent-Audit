EXPECTED_REMAINING_SLICES = sorted([
    ("oracle_pnpm.py", "if (r[0], r[1]) in pnpm_parents and r[:3] in"),
    ("oracle_pnpm.py", "set(x[:3] for x in pnpm_recs)]"),
    ("oracle_pnpm.py", "if (r[0], r[1]) in pnpm_parents and r[:3] not in"),
    ("oracle_pnpm.py", "set(x[:3] for x in pnpm_recs)]"),
    ("oracle_rubygems.py", "if not line[:1].isspace():"),
])


def test_no_display_truncation_slices_remain_in_oracle_diagnostics():
    found = []
    for f in sorted(TOOLS.glob("oracle_*.py")):
        for line in f.read_text(encoding="utf-8").splitlines():
            if re.search(r"\[:\d+\]", line):
                found.append((f.name, line.strip()))
    found.sort()
    assert found == EXPECTED_REMAINING_SLICES, (
        "numeric slices must be exactly the declared semantic/parsing "
        "exclusions (census audit_output/b1/logs/site_census.md E1/E2); "
        f"offenders: {[x for x in found if x not in EXPECTED_REMAINING_SLICES]}")
