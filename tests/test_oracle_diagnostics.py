# 3. gradle: deterministic ordering + consumer prefixes + no duplicates
# --------------------------------------------------------------------------
def test_gradle_deterministic_output_and_consumer_prefixes(tmp_path):
    tree = _gradle_tree(8)
    p1 = _run("gradle", "gradle-dependencies.txt", tree, [], tmp_path)
    p2 = _run("gradle", "gradle-dependencies.txt", tree, [], tmp_path)
    assert p1.stdout == p2.stdout, "diagnostic output must be deterministic"
    shown = _displayed_tuples(p1.stdout, "MISSING (VERIFIED):")
    assert shown == sorted(set(shown)), "displayed duplicates"
    og = _load_oracle("gradle")
    tfile = tmp_path / "gradle-dependencies.txt"
    tfile.write_text(tree, encoding="utf-8")
    expected, _u, _c, _d = og.expected_edges(str(tfile))
    full = [{"parent_name": p, "parent_version": pv,
             "child_name": c, "child_version": cv,
             "confidence": "VERIFIED"}
            for (p, pv, c, cv) in sorted(expected)]
    ok_proc = _run("gradle", "gradle-dependencies.txt", tree, full,
                   tmp_path)
    for prefix in GRADLE_PASS_PREFIXES:
        assert prefix in ok_proc.stdout, f"consumer prefix lost: {prefix}"


