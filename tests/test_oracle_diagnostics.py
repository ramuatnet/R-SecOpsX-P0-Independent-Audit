import importlib.util
import json
import re
import subprocess
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent.parent / "tools"

TUPLE_RE = re.compile(r"\('([^']*)', '([^']*)', '([^']*)', '([^']*)'\)")

# established consumer-prefix strings (tests/test_lock_graph_gradle.py
# asserts these; B-1 must not invalidate them)
GRADLE_PASS_PREFIXES = ("WRONG (VERIFIED):   0", "MISSING (VERIFIED): 0",
                        "MISSING (VERIFIED)", "ORACLE RESULT: PASS")


def _load_oracle(name):
    spec = importlib.util.spec_from_file_location(
        f"oracle_{name}_b1", TOOLS / f"oracle_{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _run(oracle_name, evidence_name, evidence_text, payload_obj, tmp_path):
    ev = tmp_path / evidence_name
    ev.write_text(evidence_text, encoding="utf-8")
    pl = tmp_path / "payload.json"
    pl.write_text(json.dumps(payload_obj), encoding="utf-8")
    proc = subprocess.run(
        [sys.executable, "-I", str(TOOLS / f"oracle_{oracle_name}.py"),
         str(ev), str(pl)],
        capture_output=True, text=True)
    return proc


def _displayed_tuples(stdout, label):
    """Sorted 4-tuples shown on the diagnostic line starting with label."""
    line = next((l for l in stdout.splitlines() if l.startswith(label)), "")
    return sorted(TUPLE_RE.findall(line))


def _gradle_tree(n):
    children = "".join(f"|    +--- org.x:child-{i}:2.0.{i}\n" for i in range(n))
    return ("> Task :app:dependencies\n\nruntimeClasspath\n"
            "+--- org.x:parent:1.0\n" + children)


def _maven_tree(n):
    children = "".join(
        f"+- com.example:lib-{i}:jar:2.0.{i}:compile\n" for i in range(n))
    return "com.example:app:jar:1.0.0\n" + children


def _cargo_lock(n):
    deps = "".join(f' "lib-{i}",\n' for i in range(n))
    libs = "".join(
        f'[[package]]\nname = "lib-{i}"\nversion = "2.0.{i}"\n\n'
        for i in range(n))
    return ('# This file is automatically @generated by Cargo.\n'
            'version = 4\n\n[[package]]\nname = "app"\nversion = "1.0.0"\n'
            f'dependencies = [\n{deps}]\n\n{libs}')


def _go_graph(n):
    return "".join(f"app@v1.0.0 lib-{i}@v2.0.{i}\n" for i in range(n))


# --------------------------------------------------------------------------
# 1. gradle: long collections display in full and round-trip exactly
# --------------------------------------------------------------------------
def test_gradle_long_missing_collection_displays_all_entries(tmp_path):
    tree = _gradle_tree(8)
    og = _load_oracle("gradle")
    tfile = tmp_path / "gradle-dependencies.txt"
    tfile.write_text(tree, encoding="utf-8")
    expected, _unres, _cons, _direct = og.expected_edges(str(tfile))
    assert len(expected) == 8, f"fixture sanity: {sorted(expected)}"
    proc = _run("gradle", "gradle-dependencies.txt", tree, [], tmp_path)
    out = proc.stdout
    assert proc.returncode == 1, out + proc.stderr  # missing != 0 -> FAIL
    count_line = next(l for l in out.splitlines()
                      if l.startswith("MISSING (VERIFIED):"))
    shown = _displayed_tuples(out, "MISSING (VERIFIED):")
    assert int(count_line.split(":")[1].split()[0]) == 8, count_line
    assert shown == sorted(expected), (
        f"displayed {len(shown)} of 8; full evidence must be displayed: "
        f"{shown}")
    assert len(shown) == len(set(shown)), "displayed duplicates"


# --------------------------------------------------------------------------
# 2. gradle: zero-entry and small-entry cases stay correct (preservation)
# --------------------------------------------------------------------------
def test_gradle_zero_and_small_collections_display_completely(tmp_path):
    tree = _gradle_tree(8)
    og = _load_oracle("gradle")
    tfile = tmp_path / "gradle-dependencies.txt"
    tfile.write_text(tree, encoding="utf-8")
    expected, _u, _c, _d = og.expected_edges(str(tfile))
    full = [{"parent_name": p, "parent_version": pv,
             "child_name": c, "child_version": cv,
             "confidence": "VERIFIED"}
            for (p, pv, c, cv) in sorted(expected)]
    # zero missing: exact payload -> PASS, empty detail list
    proc = _run("gradle", "gradle-dependencies.txt", tree, full, tmp_path)
    assert proc.returncode == 0, proc.stdout + proc.stderr
    zero_line = next(l for l in proc.stdout.splitlines()
                     if l.startswith("MISSING (VERIFIED):"))
    assert "MISSING (VERIFIED): 0" in zero_line and "[]" in zero_line
    assert "ORACLE RESULT: PASS" in proc.stdout
    # small collection (3 of 8 missing): all 3 displayed (worked before
    # the limit too -- preservation).  Payload covers 5 of 8 -> exactly 3
    # missing (below the old 5-entry display limit).
    proc = _run("gradle", "gradle-dependencies.txt", tree, full[:5],
                tmp_path)
    shown = _displayed_tuples(proc.stdout, "MISSING (VERIFIED):")
    assert shown == sorted(expected - set(map(tuple, [(
        e["parent_name"], e["parent_version"], e["child_name"],
        e["child_version"]) for e in full[:5]]))), shown
    assert len(shown) == 3


